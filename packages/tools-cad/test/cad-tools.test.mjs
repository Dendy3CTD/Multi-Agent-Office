test("task dispatcher exposes CAD tools only to CAD-capable employees", async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-capability-"));
  t.after(() => rm(workspaceRoot, { recursive: true, force: true }));
  const cad = createTaskCadDispatcher({ projectId: "project-cad", taskId: "task-cad", executionId: "exec-cad", workspaceRoot, employee: { id: "cad-engineer", professionId: "cad-engineer", skills: ["cad", "3d"] } });
  const analyst = createTaskCadDispatcher({ projectId: "project-cad", taskId: "task-analysis", executionId: "exec-analysis", workspaceRoot, employee: { id: "analyst", professionId: "analyst", skills: ["research"] } });
  assert.ok(cad.tools.some(tool => tool.id === "cad.model.create"));
  assert.equal(cad.mcpServer.name, "mao_cad");
  assert.deepEqual(cad.mcpServer.allowedTools, cad.tools.map(tool => tool.id));
  assert.deepEqual(analyst.tools, []);
  assert.equal(analyst.mcpServer, undefined);
});

test("FreeCAD creates a measured ESP32-C3 enclosure and exports files that are re-read", { timeout: 180_000 }, async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-geometry-"));
  t.after(() => rm(workspaceRoot, { recursive: true, force: true }));
  await mkdir(join(workspaceRoot, "fixtures"));
  await cp(fileURLToPath(new URL("./fixtures/esp32-c3-supermini-enclosure.json", import.meta.url)), join(workspaceRoot, "fixtures/enclosure.json"));
  const tools = createCadTools({ workspaceRoot, taskId: "test-enclosure" });
  const call = async (id, input) => await tools.get(id).execute(input);
  const capabilities = await call("cad.capabilities", {});
  assert.equal(capabilities.status, "PASS", JSON.stringify(capabilities));
  assert.match(JSON.stringify(capabilities.checkedParameters), /FreeCADCmd\.version.*1\.0\.0/);
  assert.equal(capabilities.checkedParameters.find(item => item.parameter === "drawing.pdf")?.value, true);
  assert.equal(capabilities.checkedParameters.find(item => item.parameter === "glb.independentValidator")?.value, false);
  const created = await call("cad.model.create", { spec: "fixtures/enclosure.json" });
  assert.equal(created.status, "PASS", JSON.stringify(created));
  assert.ok(created.unconfirmedParameters.some(item => item.parameter.includes("mountHole")), JSON.stringify(created.unconfirmedParameters));
  assert.ok(created.createdFiles.some(path => path.endsWith(".FCMacro")));
  assert.ok(created.createdFiles.some(path => path.endsWith(".FCStd")));
  assert.ok(created.createdFiles.some(path => path.endsWith(".step")));
  assert.ok(created.createdFiles.some(path => path.endsWith(".stl")));
  const model = created.createdFiles.find(path => path.endsWith(".FCStd"));
  assert.ok(model);

  const validated = await call("cad.model.validate", { model });
  assert.equal(validated.status, "NEEDS_REVIEW", JSON.stringify(validated));
  assert.ok(validated.unconfirmedParameters.some(item => item.parameter.includes("mountHole")));
  const assembly = await call("cad.assembly.inspect", { model });
  assert.equal(assembly.status, "NEEDS_REVIEW", JSON.stringify(assembly));
  assert.ok(assembly.checkedParameters.some(item => item.parameter === "intersectionsMm3"));
  const step = await call("cad.export.step", { model });
  assert.equal(step.status, "PASS", JSON.stringify(step));
  const stl = await call("cad.export.stl", { model });
  assert.equal(stl.status, "PASS", JSON.stringify(stl));
  const glb = await call("cad.export.glb", { model });
  assert.equal(glb.status, "PASS", JSON.stringify(glb));
  assert.ok(glb.createdFiles.some(path => path.endsWith(".glb")));
  const drawing = await call("cad.drawing.generate", { model });
  assert.equal(drawing.status, "PASS", JSON.stringify(drawing));
  if (drawing.createdFiles.some(path => path.endsWith(".pdf"))) {
    assert.equal(drawing.checkedParameters.find(item => item.parameter === "drawing.pdf.status")?.value, "PASS");
    assert.equal(drawing.checkedParameters.find(item => item.parameter === "drawing.pdf.pages")?.value, 1);
    assert.equal(drawing.checkedParameters.find(item => item.parameter === "drawing.pdf.dimensionsPresent")?.value, true);
  } else assert.equal(drawing.checkedParameters.find(item => item.parameter === "drawing.pdf.status")?.value, "BLOCKED");
  assert.ok(drawing.createdFiles.some(path => path.endsWith(".pdf")), "the current Debian host has Chromium, pdfinfo, and pdftotext installed");
  const preview = await call("cad.render.preview", { model });
  assert.equal(preview.status, "PASS", JSON.stringify(preview));

  for (const result of [step, stl, glb, drawing, preview]) for (const relativePath of result.createdFiles) {
    const bytes = await readFile(join(workspaceRoot, relativePath));
    assert.ok(bytes.length > 0, `${relativePath} is empty`);
  }
  const geometry = JSON.parse(await readFile(join(workspaceRoot, created.createdFiles.find(path => path.endsWith("geometry.json"))), "utf8"));
  assert.equal(geometry.checks.stepReimport, true);
  assert.equal(geometry.checks.stlReimport, true);
  assert.equal(geometry.checks.noBaseCoverIntersection, true);
});

test("FreeCAD builds generic parameterized parts from bounded primitives and boolean features", { timeout: 180_000 }, async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-parametric-"));
  t.after(() => rm(workspaceRoot, { recursive: true, force: true }));
  await mkdir(join(workspaceRoot, "fixtures"));
  await cp(fileURLToPath(new URL("./fixtures/parametric-bracket.json", import.meta.url)), join(workspaceRoot, "fixtures/bracket.json"));
  const tools = createCadTools({ workspaceRoot, taskId: "parametric-bracket" });
  const result = await tools.get("cad.model.create").execute({ spec: "fixtures/bracket.json" });
  assert.equal(result.status, "PASS", JSON.stringify(result));
  assert.ok(result.createdFiles.some(path => path.endsWith(".FCStd")));
  assert.ok(result.createdFiles.some(path => path.endsWith(".step")));
  assert.ok(result.createdFiles.some(path => path.endsWith(".stl")));
  const geometryPath = result.createdFiles.find(path => path.endsWith("geometry.json"));
  const geometry = JSON.parse(await readFile(join(workspaceRoot, geometryPath), "utf8"));
  assert.equal(geometry.checks.stepReimport, true);
  assert.equal(geometry.checks.stlReimport, true);
  assert.equal(geometry.checks.allPartsValid, true);
  assert.ok(geometry.parameters.outerMm.width > 0);
  const modelPath = result.createdFiles.find(path => path.endsWith(".FCStd"));
  const validated = await tools.get("cad.model.validate").execute({ model: modelPath });
  assert.equal(validated.status, "PASS", JSON.stringify(validated));
  const drawing = await tools.get("cad.drawing.generate").execute({ model: modelPath });
  assert.equal(drawing.status, "PASS", JSON.stringify(drawing));
  const svg = await readFile(join(workspaceRoot, drawing.createdFiles[0]), "utf8");
  assert.match(svg, /MAO Hybrid parametric part/);
  assert.doesNotMatch(svg, /ESP32-C3/);
});

test("FreeCAD builds a multi-body controller enclosure from constrained sketches and feature operations", { timeout: 180_000 }, async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-assembly-"));
  t.after(() => rm(workspaceRoot, { recursive: true, force: true }));
  await mkdir(join(workspaceRoot, "fixtures"));
  await cp(fileURLToPath(new URL("./fixtures/low-voltage-controller-assembly.json", import.meta.url)), join(workspaceRoot, "fixtures/controller.json"));
  const tools = createCadTools({ workspaceRoot, taskId: "controller-assembly" });
  const created = await tools.get("cad.model.create").execute({ spec: "fixtures/controller.json" });
  assert.equal(created.status, "PASS", JSON.stringify(created));
  assert.ok(created.unconfirmedParameters.some(item => /controller-board dimensions/.test(item.parameter)));
  for (const ext of [".FCStd", ".step", ".stl"]) assert.ok(created.createdFiles.some(path => path.endsWith(ext)), ext);
  const assumptionTable = created.createdFiles.find(path => path.endsWith("assumptions.csv"));
  assert.ok(assumptionTable, "assumptions table CSV must be created");
  assert.match(await readFile(join(workspaceRoot, assumptionTable), "utf8"), /controller-board dimensions/);
  const reportPath = created.createdFiles.find(path => path.endsWith("geometry.json"));
  const report = JSON.parse(await readFile(join(workspaceRoot, reportPath), "utf8"));
  assert.equal(report.checks.allComponentsValid, true);
  assert.equal(report.checks.noVolumeCollisions, true);
  assert.equal(report.checks.stepReimport, true);
  assert.equal(report.checks.stlReimport, true);
  assert.equal(report.components.length, 3);
  assert.ok(report.featureHistory.some(item => item.type === "PartDesign::Pad"));
  assert.ok(report.featureHistory.some(item => item.type === "PartDesign::Pocket"));
  assert.ok(report.featureHistory.some(item => item.type === "Sketcher::SketchObject" && item.fullyConstrained));
  assert.equal(report.componentDimensions[0].status, "NEEDS_REVIEW");
  assert.ok(report.clearances.some(item => item.components.includes("base") && item.components.includes("cover") && item.distanceMm >= 0.2));
  assert.equal(report.clearanceChecks[0].status, "NEEDS_REVIEW");
  assert.ok(Math.abs(report.clearanceChecks[0].measuredGapMm - 0.3) <= 0.1);
  const modelPath = created.createdFiles.find(path => path.endsWith(".FCStd"));
  const glbResult = await tools.get("cad.export.glb").execute({ model: modelPath });
  assert.equal(glbResult.status, "PASS", JSON.stringify(glbResult));
  assert.equal(glbResult.checkedParameters.find(item => item.parameter === "glb.structure.status")?.value, "PASS");
  assert.equal(glbResult.checkedParameters.find(item => item.parameter === "glb.geometry.status")?.value, "PASS");
  assert.equal(glbResult.checkedParameters.find(item => item.parameter === "glb.visual.status")?.value, "NOT_VERIFIED");
  assert.equal(glbResult.checkedParameters.find(item => item.parameter === "glb.independent.status")?.value, "BLOCKED");
  const assembly = await tools.get("cad.assembly.inspect").execute({ model: modelPath });
  assert.equal(assembly.status, "NEEDS_REVIEW", JSON.stringify(assembly));
});

test("FreeCAD applies valid fillet and chamfer features and records their feature history", { timeout: 180_000 }, async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-edge-features-"));
  t.after(() => rm(workspaceRoot, { recursive: true, force: true }));
  await mkdir(join(workspaceRoot, "fixtures"));
  await cp(fileURLToPath(new URL("./fixtures/fillet-chamfer.json", import.meta.url)), join(workspaceRoot, "fixtures/edge-features.json"));
  const tools = createCadTools({ workspaceRoot, taskId: "edge-features" });
  const created = await tools.get("cad.model.create").execute({ spec: "fixtures/edge-features.json" });
  assert.equal(created.status, "PASS", JSON.stringify(created));
  const geometryPath = created.createdFiles.find(path => path.endsWith("geometry.json"));
  const geometry = JSON.parse(await readFile(join(workspaceRoot, geometryPath), "utf8"));
  assert.ok(geometry.featureHistory.some(item => item.type === "PartDesign::Fillet" && item.valid));
  assert.ok(geometry.featureHistory.some(item => item.type === "PartDesign::Chamfer" && item.valid));
  const rotated = geometry.components.find(item => item.id === "chamfered-block");
  assert.ok(Math.abs(rotated.boundsMm.x - 10) < 1e-6);
  assert.ok(Math.abs(rotated.boundsMm.y - 20) < 1e-6);
  assert.equal(geometry.componentDimensions[0].status, "PASS");
  assert.ok(geometry.componentDimensions[0].absoluteDeltaMm.width < 1e-6);
});

test("missing FreeCAD and workspace path escapes return structured BLOCKED results", async (t) => {
  const workspaceRoot = await mkdtemp(join(tmpdir(), "mao-cad-negative-"));
  const outside = await mkdtemp(join(tmpdir(), "mao-cad-outside-"));
  t.after(async () => { await rm(workspaceRoot, { recursive: true, force: true }); await rm(outside, { recursive: true, force: true }); });
  await mkdir(join(workspaceRoot, "fixtures"));
  await cp(fileURLToPath(new URL("./fixtures/esp32-c3-supermini-enclosure.json", import.meta.url)), join(workspaceRoot, "fixtures/enclosure.json"));
  await writeFile(join(outside, "enclosure.json"), "{}");
  await symlink(join(outside, "enclosure.json"), join(workspaceRoot, "escape.json"));
  const unavailable = createCadTools({ workspaceRoot, commandAvailability: () => false });
  const absent = await unavailable.get("cad.capabilities").execute({});
  assert.equal(absent.status, "BLOCKED");
  assert.match(absent.reason, /FreeCADCmd.*not installed/i);
  const tools = createCadTools({ workspaceRoot });
  const escaped = await tools.get("cad.model.create").execute({ spec: "escape.json" });
  assert.equal(escaped.status, "BLOCKED");
  assert.match(escaped.stderr, /outside|symlink/i);
  assert.equal(escaped.executed, false);
  await writeFile(join(workspaceRoot, "fixtures", "malformed.json"), JSON.stringify({ modelId: "wrong-model", units: "inches" }));
  const malformed = await tools.get("cad.model.create").execute({ spec: "fixtures/malformed.json" });
  assert.equal(malformed.status, "BLOCKED");
  assert.match(malformed.reason, /modelId=.*units=mm/);
  assert.equal(malformed.executed, false);
  await writeFile(join(workspaceRoot, "fixtures", "invalid-primitive.json"), JSON.stringify({ modelId: "mao-parametric-part", units: "mm", parameters: { parts: [{ id: "invalid", base: { type: "sphere", diameterMm: 1, heightMm: 1 }, features: [] }] }, assumptions: [] }));
  const invalidPrimitive = await tools.get("cad.model.create").execute({ spec: "fixtures/invalid-primitive.json" });
  assert.equal(invalidPrimitive.status, "BLOCKED");
  assert.match(invalidPrimitive.reason, /primitive type must be box or cylinder/i);
  assert.equal(invalidPrimitive.executed, false);
  assert.throws(() => createCadTools({ workspaceRoot, timeoutMs: 999 }), /timeoutMs/);
  assert.throws(() => createCadTools({ workspaceRoot, maxOutputBytes: 5 * 1024 * 1024 }), /maxOutputBytes/);
});
